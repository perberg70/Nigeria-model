"""Render the baseline as the JavaScript block the prototype embeds, and read it back."""

from __future__ import annotations

import json
from collections.abc import Sequence

from scenario_data import interp

from .builder import LOW, BaselineResult

BLOCK1 = "/* ---- BLOCK 1: drop-in replacement for NGA_DATA.emissions ---- */"
BLOCK2 = "/* ---- BLOCK 2: NGA_DATA.power.sspBaseline ---- */"
BLOCK3 = "/* ---- BLOCK 3: NGA_DATA.power.popSSP, historical reference plus forecasts ---- */"
BLOCK4 = "/* ---- BLOCK 4: NGA_DATA.health.pollutingIdxSSP ---- */"


def _cumulative(years: Sequence[int], mt: Sequence[float], start: int, end_year: int) -> int:
    """Cumulative Mt from `start` to the end year, trapezoid on the annual interpolation,
    as the figure printed under the emissions chart."""
    d = dict(zip(years, mt, strict=False))
    return int(round(sum((interp(y, d) + interp(y + 1, d)) / 2.0 for y in range(start, end_year))))


def render_block(result: BaselineResult) -> str:
    """The four generated blocks, preceded by a do-not-edit header."""

    p, years, block = result.params, result.years, result.block
    out = [
        "/* GENERATED by scripts/run_ssp_baseline.py from src/ssp_baseline --\n"
        "   do not hand-edit, re-run to regenerate.\n"
        "   Economy-wide emissions are %s national drivers through the\n"
        "   stage-sensitive Burke & Csereklyei aggregate-energy relation;\n"
        "   an R10 efficiency residual (income effect removed) is an efficiency /\n"
        "   technology proxy; R10 carbon intensity is not transferred.\n"
        "   Sources, the transfer rule, the denominator decision and what is\n"
        "   deliberately NOT carried are in src/ssp_baseline/builder.py. */\n\n" % p.region_name
    ]

    out.append(BLOCK1 + "\n")
    out.append("  emissions:{\n    years:%s,\n" % json.dumps(years))
    for pid in p.markers:
        out.append(
            "    %s:{mt:%s, populationFactor:%s, gdpPerCapitaFactor:%s,\n"
            "       demandFactor:%s, r10FinalEnergyIntensityFactor:%s,\n"
            "       incomeElasticity:%s, cum:%d},\n"
            % (
                pid,
                json.dumps(block[pid]["emisMt"]),
                json.dumps(block[pid]["populationFactor"]),
                json.dumps(block[pid]["gdpPerCapitaFactor"]),
                json.dumps(block[pid]["demandFactor"]),
                json.dumps(block[pid]["r10FinalEnergyIntensityFactor"]),
                json.dumps(block[pid]["incomeElasticity"]),
                _cumulative(years, block[pid]["emisMt"], 2025, p.end_year),
            )
        )
    out.append("  },\n\n")

    out.append(BLOCK2 + "\n")
    out.append("         sspBaseline:{\n           years:%s,\n" % json.dumps(years))
    for pid in p.markers:
        r = block[pid]
        out.append("           %s:{elecShare:%s,\n" % (pid, json.dumps(r["elecShare"])))
        out.append("             lowShare:%s,\n" % json.dumps(r["lowShare"]))
        out.append("             energyTJ:%s,\n" % json.dumps(r["energyTJ"]))
        out.append(
            "             r10EnergyIntensityFactor:%s,\n"
            % json.dumps(r["r10EnergyIntensityFactor"])
        )
        out.append("             gensetFossil:%s,\n" % json.dumps(r["gensetFossil"]))
        out.append(
            "             lowMix:{%s}},\n"
            % ",".join("%s:%s" % (n, json.dumps(r["lowMix"][n])) for n in LOW)
        )
    out.append("         },\n\n")

    out.append(BLOCK3 + "\n")
    out.append("         popSSP:{\n")
    for narr in p.narratives:
        ys = result.pop[narr]
        out.append(
            "           %s:{%s},\n"
            % (narr, ",".join("%d:%d" % (y, round(ys[y])) for y in sorted(ys)))
        )
    out.append("         },\n\n")

    out.append(BLOCK4 + "\n")
    out.append(
        "    pollutingIdxSSP:{\n      eps:%s, years:%s,\n" % (p.cook_elasticity, json.dumps(years))
    )
    for narr in p.narratives:
        out.append("      %s:%s,\n" % (narr, json.dumps(result.cook[narr])))
    out.append("    },\n")
    return "".join(out)


def block_years(text: str) -> list[int]:
    """The year grid of BLOCK 2 (``sspBaseline.years``), read back."""

    i = text.index("sspBaseline:{")
    j = text.index("years:[", i) + len("years:[")
    return [int(x) for x in text[j : text.index("]", j)].split(",")]


def block_series(text: str, pathway: str, key: str) -> list[float]:
    """One annual series of BLOCK 2 (e.g. ``energyTJ``) for one pathway, read back."""

    i = text.index("%s:{elecShare" % pathway)
    j = text.index("%s:[" % key, i)
    k = text.index("]", j)
    return [float(x) for x in text[j + len(key) + 2 : k].split(",")]
